"""cdk-nag (AwsSolutions, v3 Validations API) acknowledgements.

Each entry is attached to the construct that triggers it (never stack-wide) and its finding id is
built from the stack's own values (logical ids, prefix, region/account tokens), so another
resource_prefix, region or Greengrass core count still synthesises cleanly. An entry whose
construct path does not exist raises, so the list cannot drift silently. SECURITY-NOTES.md lists the
same acknowledgements with their reasons.
"""

from __future__ import annotations

from aws_cdk import Acknowledgment, Token, Validations

P = "AwsSolutions::AwsSolutions-"

R_OBJ = "Object-level ARNs under one fixed prefix of this stack's own data bucket; S3 object ARNs need the '/*' form."
R_LOGS = "Log streams of this function's own log group (stream names are generated by Lambda)."
R_ENDPOINT = "iot:DescribeEndpoint does not support resource-level permissions; the call only returns the account's data endpoint."
R_TOPIC = ("Cloud-to-device replies go to edge/<thing>/... for whichever device asked; thing names are generated, "
           "so the device segment is a wildcard. The device side is isolated by the thing policy variable.")
R_ECR_AUTH = "ecr:GetAuthorizationToken does not support resource-level permissions; image pulls are scoped to the two repositories."
R_SFN_FN = "CDK LambdaInvoke grant: the function ARN plus ':*' for its versions/aliases; limited to this workflow's own functions."
R_SFN_XRAY = "X-Ray PutTraceSegments/PutTelemetryRecords/GetSampling* (tracing enabled) do not support resource-level permissions."


def _ack(construct, finding: str, reason: str) -> None:
    Validations.of(construct).acknowledge(Acknowledgment(id=P + finding, reason=reason))


def acknowledge(stack) -> None:
    lid = lambda c: stack.get_logical_id(c.node.default_child)  # noqa: E731
    bucket = f"<{lid(stack.bucket)}.Arn>"
    acct = "<AWS::AccountId>" if Token.is_unresolved(stack.account) else stack.account
    region = "<AWS::Region>" if Token.is_unresolved(stack.region) else stack.region
    part = "<AWS::Partition>" if Token.is_unresolved(stack.partition) else stack.partition
    iot_topic = "arn:<AWS::Partition>:iot:<AWS::Region>:<AWS::AccountId>:topic/edge/*/"

    # ---- Lambda roles
    obj_grants = {
        "upload_url": ["uploads"], "validate_input": ["uploads", "work"], "analyze": ["work"],
        "finalize": ["work", "results", "shelf"], "fallback": ["work", "results", "shelf"],
    }
    for name, role in stack.fn_roles.items():
        pol = role.node.find_child("DefaultPolicy")
        _ack(pol, f"IAM5[Resource::<{lid(stack.fn_logs[name])}.Arn>:*]", R_LOGS)
        for p in obj_grants.get(name, []):
            _ack(pol, f"IAM5[Resource::{bucket}/{p}/*]", R_OBJ)
        if name in ("upload_url", "finalize", "fallback"):
            _ack(pol, "IAM5[Resource::*]", R_ENDPOINT)
    _ack(stack.fn_roles["upload_url"].node.find_child("DefaultPolicy"), f"IAM5[Resource::{iot_topic}upload/url]", R_TOPIC)
    for name in ("finalize", "fallback"):
        _ack(stack.fn_roles[name].node.find_child("DefaultPolicy"), f"IAM5[Resource::{iot_topic}results]", R_TOPIC)

    # ---- workflow role
    wf = stack.state_machine.role.node.find_child("DefaultPolicy")
    for key in ("validate_input", "analyze", "finalize", "fallback"):
        _ack(wf, f"IAM5[Resource::<{lid(stack.fn[key])}.Arn>:*]", R_SFN_FN)
    _ack(wf, "IAM5[Resource::*]", R_SFN_XRAY)

    # ---- IoT / Greengrass / simulators
    _ack(stack.provisioning_role, "IAM4[Policy::arn:<AWS::Partition>:iam::aws:policy/service-role/AWSIoTThingsRegistration]",
         "AWS managed policy documented for fleet provisioning template roles; the trust policy is limited to this "
         "template ARN with aws:SourceAccount and aws:SourceArn.")
    _ack(stack.tes_role.node.find_child("DefaultPolicy"), f"IAM5[Resource::{bucket}/gg-artifacts/*]",
         "Greengrass cores download this project's component artifacts from one prefix of the data bucket.")
    _ack(stack.task_roles["simulator"].node.find_child("DefaultPolicy"), f"IAM5[Resource::{bucket}/loadtest/*]",
         "Simulator tasks write their JSON reports under one prefix (run id / task index are generated).")
    for td in stack.task_defs.values():
        _ack(td.execution_role.node.find_child("DefaultPolicy"), "IAM5[Resource::*]", R_ECR_AUTH)
        _ack(td, "ECS2", "Environment variables carry only names (prefix, template, secret id, bucket); certificate "
                         "material is fetched from Secrets Manager by the task role at start-up.")
    for s in [stack.claim_secret, *stack.gg_secrets]:
        _ack(s, "SMG4", "Holds device certificate material written by scripts/setup_identities.py; rotation means "
                        "issuing a new IoT certificate (documented revocation flow), not a Secrets Manager rotation.")

    # ---- queues
    _ack(stack.telemetry, "SQS3", "Heartbeat sink for loss measurement only; messages are counted and expire, a "
                                  "dead-letter queue would add nothing.")
    _ack(stack.rule_errors, "SQS3", "This queue is itself the error destination of the IoT rules.")

    # ---- image build
    cb = stack.image_build
    _ack(cb, "CB4", "Build artifacts are images in ECR (scan on push); logs go to CloudWatch Logs. A customer managed "
                    "KMS key is in the hardening checklist.")
    cbp = cb.role.node.find_child("DefaultPolicy")
    for a in ("GetBucket*", "GetObject*", "List*"):
        _ack(cbp, f"IAM5[Action::s3:{a}]", "CDK asset-read grant for the image-source asset object in the CDK "
                                         "bootstrap assets bucket.")
    _ack(cbp, "IAM5[Resource::*]", R_ECR_AUTH)
    cb_id = stack.get_logical_id(cb.node.default_child)
    _ack(cbp, f"IAM5[Resource::arn:{part}:codebuild:{region}:{acct}:report-group/<{cb_id}>-*]",
         "CodeBuild default report-group permission scoped to this project.")
    _ack(cbp, f"IAM5[Resource::arn:{part}:logs:{region}:{acct}:log-group:/aws/codebuild/<{cb_id}>:*]",
         "CodeBuild default log-group permission scoped to this project.")
